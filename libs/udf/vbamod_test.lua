-- vbamod_test.lua — VBA 运行时库断言测试（VBA 语义锚点）
-- 跑法: luajit vbamod_test.lua  （退出码 0=全过）
-- 跑法: cd libs/udf && luajit vbamod_test.lua
local vba = dofile('vbamod.lua')
local ok, fail = 0, 0
local function eq(name, got, want)
  local g, w = tostring(got), tostring(want)
  if type(got) == "number" and type(want) == "number" and math.abs(got - want) < 1e-6 then g = w end
  if g == w then ok = ok + 1
  else fail = fail + 1; print(string.format("FAIL %-28s got=[%s] want=[%s]", name, g, w)) end
end

-- ===== Strings =====
