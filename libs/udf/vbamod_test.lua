eq("InStr", vba.InStr("hello", "l"), 3)
eq("InStr miss", vba.InStr("hello", "x"), 0)
eq("InStr start", vba.InStr(4, "hello", "l"), 4)
eq("InStr empty", vba.InStr("hello", ""), 1)
eq("InStr empty4", vba.InStr(4, "hello", ""), 4)
